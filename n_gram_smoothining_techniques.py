def perplexity(tokens, k):
    pairs = list(bigrams(tokens))
    if not pairs:
        return float("inf")

    log_sum = 0
    for w1, w2 in pairs:
        p = probability(w1, w2, k)
        log_sum += math.log(p)

    return math.exp(-log_sum / len(pairs))

