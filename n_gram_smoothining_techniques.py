def addk_prob(w1, w2, k):
    """P(w2 | w1) using Add-k smoothing (0 < k <= 1 typically)"""
    numerator   = bigram_freq[(w1, w2)] + k
    denominator = unigram_freq[w1] + (k * vocab_size)
    return numerator / denominator

