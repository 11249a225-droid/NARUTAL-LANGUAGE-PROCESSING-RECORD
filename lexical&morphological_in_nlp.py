# Small Lexicon-Based FST (Analysis + Generation)

lexicon = {
    "cat": {"plural": "cats"},
    "dog": {"plural": "dogs"},
    "book": {"plural": "books"},
    "car": {"plural": "cars"},
    "apple": {"plural": "apples"},
    "child": {"plural": "children"},
    "mouse": {"plural": "mice"},
    "goose": {"plural": "geese"},
    "play": {"past": "played"},
    "walk": {"past": "walked"},
    "eat": {"past": "ate"},
    "go": {"past": "went"},
    "run": {"past": "ran"},
    "write": {"past": "wrote"},
    "see": {"past": "saw"}
}

# Analysis
def analyze(word):
    for base, forms in lexicon.items():
        if word == base:
            return f"{word} -> Base: {base}"
        if word in forms.values():
            return f"{word} -> Base: {base}"
    return "Not Found"

# Generation
def generate(base, form):
    return lexicon.get(base, {}).get(form, "Not Found")

# Test
print(analyze("children"))
print(analyze("went"))
print(generate("child", "plural"))
print(generate("go", "past"))

