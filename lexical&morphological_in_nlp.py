# Dictionary for irregular plurals
irregular_plurals = {
    "mice": "mouse",
    "geese": "goose",
    "children": "child",
    "men": "man",
    "women": "woman",
    "teeth": "tooth",
    "feet": "foot",
    "oxen": "ox"
}

# Dictionary for irregular past tense verbs
irregular_past = {
    "went": "go",
    "ate": "eat",
    "ran": "run",
    "came": "come",
    "saw": "see",
    "bought": "buy",
    "gave": "give",
    "took": "take",
    "wrote": "write",
    "drank": "drink"
}

def morphological_analyzer(word):
    word = word.lower()

    # Check irregular plural nouns
    if word in irregular_plurals:
        return f"{word} → {irregular_plurals[word]} (Irregular Plural)"

    # Check irregular past tense verbs
    if word in irregular_past:
        return f"{word} → {irregular_past[word]} (Irregular Past Tense)"

    # Regular plural rules
    if word.endswith("ies"):
        return f"{word} → {word[:-3] + 'y'} (Regular Plural)"

    elif word.endswith("es"):
        return f"{word} → {word[:-2]} (Regular Plural)"

    elif word.endswith("s") and len(word) > 3:
        return f"{word} → {word[:-1]} (Regular Plural)"

    # Regular past tense rules
    elif word.endswith("ied"):
        return f"{word} → {word[:-3] + 'y'} (Regular Past Tense)"

    elif word.endswith("ed"):
        return f"{word} → {word[:-2]} (Regular Past Tense)"

    elif word.endswith("ing"):
        return f"{word} → {word[:-3]} (Present Participle)"

    else:
        return f"{word} → {word} (Base Form)"


