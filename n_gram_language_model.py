import re
from collections import defaultdict, Counter

corpus = """the quick brown fox jumps over the lazy dog
the dog barks at the fox
the quick fox runs away from the dog"""

def tokenize(text):
    text = text.lower()
    return re.findall(r"[a-z']+", text)

tokens = tokenize(corpus)

# Create bigrams
bigrams = list(zip(tokens[:-1], tokens[1:]))

# Count bigrams and individual words
bigram_counts = Counter(bigrams)
unigram_counts = Counter(tokens)

# Create probability matrix
prob_matrix = defaultdict(dict)

for (word1, word2), count in bigram_counts.items():
    prob_matrix[word1][word2] = count / unigram_counts[word1]

# Get all unique words
vocabulary = sorted(set(tokens))

# Print probability matrix
print("\nBigram Probability Matrix:")
print(f"{'Word':<12}", end="")

for word in vocabulary:
    print(f"{word:<10}", end="")

print()
print("-" * (12 + 10 * len(vocabulary)))

for word1 in vocabulary:
    print(f"{word1:<12}", end="")

    for word2 in vocabulary:
        probability = prob_matrix[word1].get(word2, 0)
        print(f"{probability:<10.4f}", end="")

    print()

