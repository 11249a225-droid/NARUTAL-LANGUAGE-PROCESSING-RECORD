import nltk
import re
import random
from collections import Counter

nltk.download('gutenberg')

text = nltk.corpus.gutenberg.raw('austen-emma.txt')
tokens = re.findall(r"[a-z']+", text.lower())

# Bigram
bigrams = list(zip(tokens[:-1], tokens[1:]))
bigram_counts = Counter(bigrams)

# Trigram
trigrams = list(zip(tokens[:-2], tokens[1:-1], tokens[2:]))
trigram_counts = Counter(trigrams)

def generate_bigram(start, n=15):
    result = [start]
    for _ in range(n - 1):
        choices = [b for a, b in bigrams if a == start]
        if not choices: break
        start = random.choice(choices)
        result.append(start)
    return " ".join(result)

def generate_trigram(w1, w2, n=15):
    result = [w1, w2]
    for _ in range(n - 2):
        choices = [c for a, b, c in trigrams if a == w1 and b == w2]
        if not choices: break
        w1, w2 = w2, random.choice(choices)
        result.append(w2)
    return " ".join(result)

print("Bigram:", generate_bigram("the"))
print("Trigram:", generate_trigram("the", "man"))

def add_k_prob(w, prev, bigrams_counter, unigrams_counter, V, k):
    return (bigrams_counter.get((prev, w), 0) + k) / \
           (unigrams_counter.get(prev, 0) + k * V)

def sent_prob(sent, bigrams_counter, unigrams_counter, vocab, k):
    words = ["<s>"] + sent.split() + ["</s>"]
    p = 1
    for i in range(1, len(words)):
        p *= add_k_prob(words[i], words[i-1],
                        bigrams_counter, unigrams_counter, len(vocab), k)
    return p

vocab = list(set(tokens))

for k in [0.01, 0.1, 0.5, 1]:
    print(k, sent_prob("i like nlp", bigram_counts, unigrams, vocab, k))

def oov_rate(test, vocab):
    words = test.split()
    return sum(w not in vocab for w in words) / len(words)

print("OOV Rate:", oov_rate("i like machine learning", vocab))

