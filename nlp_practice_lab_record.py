from collections import Counter
s = ["I love NLP", "I love NLP", "I love NLP", "I love NLP"]
u = Counter()
b = Counter()
for x in s:
    w = ["<s>"] + x.split() + ["</s>"]
    u.update(w)
    b.update(zip(w, w[1:]))
p = lambda a, c: b[(a, c)] / u[a]
print("Unigrams:", {x: u[x] for x in ["<s>", "I", "love", "NLP"]})
print("Bigrams from I:", {k:v for k,v in b.items() if k[0]=="I"})
print("Bigrams from love:", {k:v for k,v in b.items() if k[0]=="love"})
print("P(I|<s>) =", p("<s>", "I"))
print("P(love|I) =", p("I", "love"))
print("P(NLP|love) =", p("love", "NLP"))
print("P(</s>|NLP) =", p("NLP", "</s>"))
print("P(I love NLP) =", p("<s>","I") * p("I","love") * p("love","NLP") * p("NLP","</s>"))