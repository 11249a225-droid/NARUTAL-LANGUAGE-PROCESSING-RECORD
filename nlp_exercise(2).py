from collections import Counter
import math

sentences = [
    "I like NLP",
    "I like Python",
    "I study NLP"
]

# Tokenize the training sentences
tokenized = [sentence.lower().split() for sentence in sentences]
words = [word for sentence in tokenized for word in sentence]

unigram_counts = Counter(words)
bigram_counts = Counter()

for sentence in tokenized:
    for i in range(len(sentence) - 1):
        bigram_counts[(sentence[i], sentence[i + 1])] += 1

print("Activity 1: Word frequency")
print(unigram_counts)

print("\nBigram frequency")
for bigram, count in bigram_counts.items():
    print(bigram, ":", count)

total_words = len(words)
vocabulary_size = len(unigram_counts)

def unigram_probability(word):
    return unigram_counts[word] / total_words

def bigram_probability(w1, w2):
    denominator = unigram_counts[w1]
    if denominator == 0:
        return 0
    return bigram_counts[(w1, w2)] / denominator

print("\nActivity 2: Unigram probabilities")
for word in unigram_counts:
    print(word, ":", round(unigram_probability(word), 4))

print("\nBigram probabilities")
for (w1, w2), count in bigram_counts.items():
    print(w1, w2, ":", round(bigram_probability(w1, w2), 4))

def sentence_probability(sentence):
    tokens = sentence.lower().split()
    probability = 1.0
    for word in tokens:
        probability *= unigram_probability(word)
    for i in range(len(tokens) - 1):
        probability *= bigram_probability(tokens[i], tokens[i + 1])
    return probability

test_sentences = ["I like NLP", "Python like I"]

print("\nActivity 3: Sentence comparison")
for sentence in test_sentences:
    print(sentence, ":", sentence_probability(sentence))

def smoothed_bigram_probability(w1, w2):
    return (bigram_counts[(w1, w2)] + 1) / (
        unigram_counts[w1] + vocabulary_size
    )

print("\nActivity 4: Laplace smoothing")
print("P(Python | like) without smoothing:",
      bigram_probability("like", "python"))
print("P(Python | like) with smoothing:",
      smoothed_bigram_probability("like", "python"))

# Activity 5: Simple comparison of grammar and statistical models
print("\nActivity 5: Model comparison")
print("Grammar model: Uses fixed grammar rules to generate valid sentences.")
print("Statistical model: Uses word and bigram frequencies to estimate probability.")

# Mini Project: Next-word prediction
def predict_next_word(prefix, number=5):
    context = prefix.lower().split()[-1]
    candidates = []
    for (w1, w2), count in bigram_counts.items():
        if w1 == context:
            candidates.append((w2, count))
    candidates.sort(key=lambda item: item[1], reverse=True)
    return [word for word, count in candidates[:number]]

print("\nMini Project: Next Word Prediction")
user_input = input("Enter a phrase (example: I like): ")
predictions = predict_next_word(user_input)

if predictions:
    print("Predicted next words:", predictions)
else:
    print("No prediction found in the training data.")