import nltk
nltk.download('punkt')
nltk.download('averaged_perceptron_tagger_eng')
sentences = [
    "The students attend classes in the classroom.",
    "A professor explains the lesson to students.",
    "The librarian works in the library.",
    "Students are playing on the campus.",
    "The computer science department organizes a workshop."
]
grammar = r"""
    NP: {<DT|PRP\$>?<JJ.*>*<NN.*>+}
    PP: {<IN><NP>}
    VP: {<VB.*>+}
"""
chunker = nltk.RegexpParser(grammar)
for sentence in sentences:
    words = nltk.word_tokenize(sentence)
    tags = nltk.pos_tag(words)
    tree = chunker.parse(tags)
    print("\nSentence:", sentence)
    print(tree)

