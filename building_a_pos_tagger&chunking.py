import nltk
nltk.download('punkt')
nltk.download('averaged_perceptron_tagger_eng')
sentence = "The boy plays in the garden."
words = nltk.word_tokenize(sentence)
tags = nltk.pos_tag(words)
grammar = r"""
    NP: {<DT>?<JJ>*<NN.*>+}
    PP: {<IN><NP>}
    VP: {<VB.*><PP>?}
"""
chunker = nltk.RegexpParser(grammar)
result = chunker.parse(tags)
print(result)
result.pretty_print()

