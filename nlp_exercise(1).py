import random

grammar = {
    "S": [["NP", "VP"]],
    "NP": [["John"], ["Mary"]],
    "VP": [["eats", "NP"]]
}

def generate(symbol):
    if symbol not in grammar:
        return symbol
    production = random.choice(grammar[symbol])
    return " ".join(generate(item) for item in production)

print("Sentences from the given grammar")
for i in range(5):
    print(generate("S"))

