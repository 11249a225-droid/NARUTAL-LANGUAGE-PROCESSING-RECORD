# Activity 5C: Simple password validation
# Rule: At least one letter and at least one digit; minimum 6 characters.
def valid_password(password):
    return (
        len(password) >= 6
        and any(ch.isalpha() for ch in password)
        and any(ch.isdigit() for ch in password)
    )

print("\nActivity 5C: Password validation")
for value in ["abc123", "abcdef", "123456", "ab12"]:
    print(value, ":", "Valid" if valid_password(value) else "Invalid")

# Activity 5D: Vowel recognition
def is_vowel(character):
    return len(character) == 1 and character.lower() in "aeiou"

print("\nActivity 5D: Vowel recognition")
