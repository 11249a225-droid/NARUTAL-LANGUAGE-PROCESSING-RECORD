def dfa_ab_star(string):
    state = "q0"

    for symbol in string:
        if state == "q0" and symbol == "a":
            state = "q1"
        elif state == "q1" and symbol == "b":
            state = "q1"
        else:
            state = "dead"

    return state == "q1"

print("Activity 1 & 2: DFA for ab*")
for test in ["a", "ab", "abb", "abbb", "b", "ba", "aa", ""]:
    print(test, ":", "Accepted" if dfa_ab_star(test) else "Rejected")

