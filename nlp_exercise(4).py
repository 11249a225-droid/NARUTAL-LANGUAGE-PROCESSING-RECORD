def simulate_dfa(string):
    state = "q0"
    print("Start state:", state)

    for symbol in string:
        if state == "q0" and symbol == "a":
            state = "q1"
        elif state == "q1" and symbol == "b":
            state = "q1"
        else:
            state = "dead"
        print("Input:", symbol, "-> State:", state)

    print("Final result:", "Accepted" if state == "q1" else "Rejected")

